import { useState } from 'react';
import { BarChartComponent } from '../components/Charts';
import api from '../services/api';

interface Scenario {
  overbooking_level: number;
  capacity: number;
  bookings: number;
  expected_noshows: number;
  expected_shows: number;
  expected_denied: number;
  expected_empty_seats: number;
  expected_revenue: number;
  expected_cost: number;
  expected_profit: number;
  probability_denied: number;
  profit_std: number;
}

interface Recommendation {
  best_overbooking_level: number;
  best_expected_profit: number;
  best_probability_denied: number;
  operational_recommendation_available: false;
  disclaimer: string;
}

interface CostParameters {
  compensation_cost: number;
  empty_seat_cost: number;
  denied_boarding_cost: number;
}

export default function Overbooking() {
  const [params, setParams] = useState({
    capacity: 180,
    bookings: 195,
    avg_noshow_prob: 0.15,
    ticket_price: 350,
    max_overbooking: 15,
  });
  const [scenarios, setScenarios] = useState<Scenario[]>([]);
  const [recommendation, setRecommendation] = useState<Recommendation | null>(null);
  const [costParameters, setCostParameters] = useState<CostParameters | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  const runSimulation = async () => {
    setLoading(true);
    setError('');
    try {
      const response = await api.simulateOverbooking(params);
      setScenarios(response.data.scenarios || []);
      setRecommendation(response.data.recommendation || null);
      setCostParameters(response.data.cost_parameters || null);
    } catch {
      setScenarios([]);
      setRecommendation(null);
      setCostParameters(null);
      setError('Simulation service is unavailable. No estimate was generated.');
    } finally {
      setLoading(false);
    }
  };

  const getRecommendation = () => {
    if (scenarios.length === 0) return null;
    return scenarios.find((scenario) => scenario.overbooking_level === recommendation?.best_overbooking_level) || null;
  };

  const chartData = scenarios.map(s => ({
    name: `+${s.overbooking_level}`,
    profit: s.expected_profit / 1000,
    cost: s.expected_cost / 1000,
    risk: s.probability_denied * 100,
  }));

  return (
    <div className="max-w-6xl mx-auto space-y-6">
      <div>
        <h1 className="text-2xl font-bold text-gray-900">Overbooking Simulator</h1>
        <p className="text-gray-500">
          Compare Monte Carlo scenarios using the no-show probability and cost assumptions you enter.
        </p>
      </div>

      {error && (
        <div role="alert" className="rounded-lg border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-700">
          {error}
        </div>
      )}

      <p className="text-sm text-gray-500">
        The no-show probability is user-entered, not generated by the prediction model. Modeled costs and profits are unverified assumptions;
        scenario rankings are not an operational recommendation or approval to sell additional tickets.
      </p>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        {/* Input Parameters */}
        <div className="card">
          <h3 className="card-header">Simulation Parameters</h3>
          <div className="space-y-4">
            <div>
              <label className="form-label">Flight Capacity</label>
              <input
                type="number"
                value={params.capacity}
                onChange={(e) => setParams({ ...params, capacity: parseInt(e.target.value) })}
                className="form-input"
              />
            </div>
            <div>
              <label className="form-label">Current Bookings</label>
              <input
                type="number"
                value={params.bookings}
                onChange={(e) => setParams({ ...params, bookings: parseInt(e.target.value) })}
                className="form-input"
              />
            </div>
            <div>
              <label className="form-label">Avg No-Show Probability</label>
              <input
                type="number"
                step="0.01"
                value={params.avg_noshow_prob}
                onChange={(e) => setParams({ ...params, avg_noshow_prob: parseFloat(e.target.value) })}
                className="form-input"
              />
            </div>
            <div>
              <label className="form-label">Avg Ticket Price ($)</label>
              <input
                type="number"
                value={params.ticket_price}
                onChange={(e) => setParams({ ...params, ticket_price: parseFloat(e.target.value) })}
                className="form-input"
              />
            </div>
            <div>
              <label className="form-label">Max Overbooking Level</label>
              <input
                type="range"
                min="5"
                max="25"
                value={params.max_overbooking}
                onChange={(e) => setParams({ ...params, max_overbooking: parseInt(e.target.value) })}
                className="w-full"
              />
              <span className="text-sm text-gray-500">+{params.max_overbooking} seats</span>
            </div>
            <button
              onClick={runSimulation}
              disabled={loading}
              className="btn btn-primary w-full py-3"
            >
              {loading ? <span className="spinner h-5 w-5" /> : 'Run Simulation'}
            </button>
          </div>
        </div>

        {/* Best-scoring scenario under the supplied assumptions */}
        <div className="lg:col-span-2 space-y-6">
          {getRecommendation() && (
            <div className="card bg-gradient-to-br from-primary-50 to-primary-100 border-primary-200">
              <h3 className="card-header">Highest-Scoring Simulated Scenario</h3>
              <p className="mt-2 text-sm text-gray-600">{recommendation?.disclaimer}</p>
              <div className="grid grid-cols-2 md:grid-cols-4 gap-4 mt-4">
                <div className="text-center">
                  <p className="text-3xl font-bold text-primary-700">+{getRecommendation()?.overbooking_level}</p>
                  <p className="text-sm text-gray-600">Simulated Level</p>
                </div>
                <div className="text-center">
                  <p className="text-3xl font-bold text-primary-700">${((getRecommendation()?.expected_profit || 0) / 1000).toFixed(1)}K</p>
                  <p className="text-sm text-gray-600">Expected Profit</p>
                </div>
                <div className="text-center">
                  <p className="text-3xl font-bold text-primary-700">{(getRecommendation()?.expected_denied || 0).toFixed(1)}</p>
                  <p className="text-sm text-gray-600">Expected Denied</p>
                </div>
                <div className="text-center">
                  <p className="text-3xl font-bold text-primary-700">{((getRecommendation()?.probability_denied || 0) * 100).toFixed(1)}%</p>
                  <p className="text-sm text-gray-600">Denied Boarding Probability</p>
                </div>
              </div>
            </div>
          )}

          {/* Chart */}
          <div className="card">
            <h3 className="card-header">Revenue vs Cost by Overbooking Level</h3>
            <BarChartComponent
              data={chartData}
              xKey="name"
              yKey="profit"
              title=""
            />
          </div>

          {/* Scenarios Table */}
          <div className="card">
            <h3 className="card-header">Scenario Comparison</h3>
            <div className="overflow-x-auto max-h-96">
              <table className="table">
                <thead className="sticky top-0 bg-gray-50">
                  <tr>
                    <th>Overbook</th>
                    <th>Total</th>
                    <th>Expected Shows</th>
                    <th>Denied Boarding</th>
                    <th>Empty Seats</th>
                    <th>Cost</th>
                    <th>Net Revenue</th>
                    <th>Risk</th>
                  </tr>
                </thead>
                <tbody>
                  {scenarios.slice(0, 16).map((s) => (
                    <tr 
                      key={s.overbooking_level}
                      className={s.overbooking_level === getRecommendation()?.overbooking_level ? 'bg-primary-50' : ''}
                    >
                      <td className="font-medium">+{s.overbooking_level}</td>
                      <td>{s.bookings}</td>
                      <td>{s.expected_shows.toFixed(1)}</td>
                      <td>
                        <span className={s.expected_denied > 1 ? 'text-red-600' : ''}>
                          {s.expected_denied.toFixed(2)}
                        </span>
                      </td>
                      <td>{s.expected_empty_seats.toFixed(2)}</td>
                      <td>${s.expected_cost.toFixed(0)}</td>
                      <td className="font-medium">${(s.expected_profit / 1000).toFixed(1)}K</td>
                      <td>
                        <span className={`badge ${
                          s.probability_denied > 0.3 ? 'badge-danger' :
                          s.probability_denied > 0.1 ? 'badge-warning' : 'badge-success'
                        }`}>
                          {(s.probability_denied * 100).toFixed(0)}%
                        </span>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        </div>
      </div>

      {/* Cost Breakdown */}
      {scenarios.length > 0 && (
        <div className="card">
          <h3 className="card-header">Cost Parameters Used</h3>
          <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
            <div className="p-4 bg-red-50 rounded-lg">
              <p className="text-sm text-red-600 font-medium">Denied Boarding Cost</p>
              <p className="text-2xl font-bold text-red-700">${(costParameters?.denied_boarding_cost || 0).toLocaleString()}</p>
              <p className="text-xs text-red-500">Per passenger denied</p>
            </div>
            <div className="p-4 bg-yellow-50 rounded-lg">
              <p className="text-sm text-yellow-600 font-medium">Empty Seat Cost</p>
              <p className="text-2xl font-bold text-yellow-700">${(costParameters?.empty_seat_cost || 0).toLocaleString()}</p>
              <p className="text-xs text-yellow-500">Per empty seat</p>
            </div>
            <div className="p-4 bg-blue-50 rounded-lg">
              <p className="text-sm text-blue-600 font-medium">Compensation</p>
              <p className="text-2xl font-bold text-blue-700">${(costParameters?.compensation_cost || 0).toLocaleString()}</p>
              <p className="text-xs text-blue-500">Per denied passenger</p>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}